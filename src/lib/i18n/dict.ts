export const DICT: Record<Lang, Record<Key, string>> = { en, bn };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const d = DICT[lang] ?? en;
  let s: string = d[key] ?? en[key] ?? key;
  if (vars && vars.n === 1) {
    const one = (d as Record<string, string>)[`${key}_one`];
    if (one) s = one;
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
  return s;
}

export type T = (key: Key, vars?: Vars) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => translate(lang, key, vars);
}

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "bn";
}
